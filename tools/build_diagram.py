#!/usr/bin/env python3
"""Generate the skill map (a Mermaid diagram) in README.md from the files in alerce/.

    python tools/build_diagram.py           # rewrite the diagram between the markers in README.md
    python tools/build_diagram.py --check   # exit 1 if README.md is out of date (CI, tests)

Everything is derived from the tree, so the figure follows every change:
* nodes: SKILL.md, every alerce/<area>/*.md, every alerce/scripts/*.py;
* labels: the "read when" text of SKILL.md's file map, else the file's first heading;
* edges: SKILL.md -> each area's index.md (or each file of an area without one) -> the area's other files;
  files generated by a repo tool are marked ⚙, and the tool is named inside their area box.
Standard library only (it runs from a git hook and in CI).
"""
from __future__ import annotations

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILL = os.path.join(ROOT, "alerce")
README = os.path.join(ROOT, "README.md")
START, END = "<!-- skill-map:start -->", "<!-- skill-map:end -->"
AREA_ORDER = ["core", "api", "tap", "classifiers", "client", "explorer", "hunter", "crossmatch", "science"]
AREA_TITLE = {"core": "core · ids, units, services", "api": "api · REST APIs", "tap": "tap · TAP / ADQL",
              "classifiers": "classifiers", "client": "client · Python client", "explorer": "explorer",
              "hunter": "hunter · candidates", "crossmatch": "crossmatch", "science": "science · playbooks",
              "scripts": "scripts · helper code"}
MAXLEN = 80


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def short(text: str) -> str:
    text = re.sub(r"`([^`]*)`", r"\1", text).replace("**", "").strip().rstrip(".")
    if len(text) <= MAXLEN:
        return text
    text = re.sub(r"\s*\([^)]*\)", "", text).strip()  # drop parentheticals before truncating
    if len(text) <= MAXLEN:
        return text
    cut = text[:MAXLEN].rsplit(" ", 1)[0].rstrip(",;:(")
    return cut + "…"


def node_id(rel: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", rel)


NBSP = "#160;"  # Mermaid entity: GitHub wraps labels at ~200px; non-breaking spaces keep each row on one line


def esc(text: str) -> str:
    return text.replace('"', "#quot;").replace(" ", NBSP).replace("-", "#8209;")  # and non-breaking hyphens


def label(name: str, desc: str) -> str:
    return f'"<b>{esc(name)}</b><br/>{esc(desc)}"' if desc else f'"<b>{esc(name)}</b>"'


def file_map_descriptions() -> dict:
    """{'tap/recipes.md': 'ready ADQL: ...'} from SKILL.md's file-map table."""
    out = {}
    for path, desc in re.findall(r"^\|\s*[├└ ]*`([a-z_\-/]+\.md)`\s*\|\s*([^|]+?)\s*\|", read(os.path.join(SKILL, "SKILL.md")), re.M):
        out[path] = desc
    return out


def first_heading(path: str) -> str:
    m = re.search(r"^#\s+(.+)$", read(path), re.M)
    return m.group(1) if m else ""


def script_description(path: str) -> str:
    m = re.search(r'"""\s*(.+?)(?:\n\n|""")', read(path), re.S)
    if not m:
        return ""
    line = m.group(1).strip().splitlines()[0]
    return line.split(" — ", 1)[-1] if " — " in line else line


def area_node(title: str, rows: list) -> str:
    """One box per area: bold title, then one line per file ("name: description")."""
    body = "<br/>".join(esc(r) for r in rows)
    return f'"<b>{esc(title)}</b><br/>{body}"'


def build() -> str:
    areas = {}
    for area in sorted(os.listdir(SKILL)):
        d = os.path.join(SKILL, area)
        if os.path.isdir(d) and area != "scripts":
            files = sorted(f for f in os.listdir(d) if f.endswith(".md"))
            if files:
                areas[area] = sorted(files, key=lambda f: (f != "index.md", f))
    order = [a for a in AREA_ORDER if a in areas] + sorted(a for a in areas if a not in AREA_ORDER)

    lines = ["```mermaid", "flowchart LR",
             f'  SKILL[{label("SKILL.md", "L0 router: service per task, invariants, file map")}]']
    edges, generated, heights = [], {}, {}
    for area in order:
        rows, tools_here = [], set()
        for f in areas[area]:
            rel = f"{area}/{f}"
            text = read(os.path.join(SKILL, rel))
            m = re.match(r"<!-- generated by (tools/[a-z_]+\.py)", text)
            if m:
                generated.setdefault(m.group(1), []).append(rel)
                tools_here.add(m.group(1))
            mark = "⚙ " if m else ("▸ " if f == "index.md" else "")
            rows.append(f"{mark}{f}: {short(first_heading(os.path.join(SKILL, rel)))}")
        # the generator is named inside the box (a separate node cost a whole empty column)
        rows += [f"⚙ = generated by {tool}" for tool in sorted(tools_here)]
        sub = AREA_TITLE.get(area, area).split(" · ")[-1]
        title = f"{area}/" + (f" · {sub}" if sub != area else "")
        lines.append(f"  {node_id(area)}[{area_node(title, rows)}]")
        heights[node_id(area)] = len(rows) + 2  # rows + title + padding

    scripts = sorted(f for f in os.listdir(os.path.join(SKILL, "scripts")) if f.endswith(".py"))
    rows = [f"{f}: {short(script_description(os.path.join(SKILL, 'scripts', f)))}" for f in scripts]
    lines.append(f"  scripts[{area_node('scripts/ · helper code', rows)}]")
    heights["scripts"] = len(rows) + 2

    # Two-sided layout: the router sits in the middle and the boxes are split between its left and right so that
    # both columns have about the same height (a one-sided fan-out left half of the figure empty). In a left-to-right
    # flowchart an edge `X --- SKILL` puts X on the left, `SKILL --- X` on the right; plain lines keep both sides alike.
    left, right, h = [], [], {"L": 0, "R": 0}
    for n in [node_id(a) for a in order] + ["scripts"]:
        side = "L" if h["L"] < h["R"] else "R"
        (left if side == "L" else right).append(n)
        h[side] += heights[n]
    for n in left:
        edges.append(f"  {n} {'-.-' if n == 'scripts' else '---'} SKILL")
    for n in right:
        edges.append(f"  SKILL {'-.-' if n == 'scripts' else '---'} {n}")

    lines += edges
    lines += ["  classDef router fill:#2e3192,color:#ffffff,stroke:#2e3192",
              "  classDef area fill:#f5f5fb,stroke:#6d6fb5,text-align:left",
              "  class SKILL router",
              f"  class {','.join([node_id(a) for a in order] + ['scripts'])} area"]
    lines.append("```")
    n_md = sum(len(v) for v in areas.values()) + 1
    caption = (f"*Skill map, generated by `tools/build_diagram.py` from the `alerce/` tree: {n_md} Markdown files in "
               f"{len(areas)} areas and {len(scripts)} scripts. The router (`SKILL.md`, centre) points to each area; ▸ marks "
               "the area's entry page, which points to the rest (an agent reads only what the task needs). ⚙ marks "
               "files generated from the alerce_tap Schema Explorer. Do not edit by hand.*")
    return "\n".join([START, "", *lines, "", caption, "", END])


def main():
    readme = read(README)
    if START not in readme or END not in readme:
        sys.exit(f"README.md has no {START} … {END} markers")
    new = readme.split(START)[0] + build() + readme.split(END, 1)[1]
    if "--check" in sys.argv:
        if new != readme:
            print("README.md skill map is out of date: run python tools/build_diagram.py")
            sys.exit(1)
        print("README.md skill map is up to date")
        return
    if new != readme:
        with open(README, "w", encoding="utf-8") as f:
            f.write(new)
        print("README.md skill map updated")
    else:
        print("README.md skill map already up to date")


if __name__ == "__main__":
    main()
