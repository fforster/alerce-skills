#!/usr/bin/env python3
"""Regenerate the skill's schema references from the alerce_tap Schema Explorer data.

Source: the "alerce_tap Schema Explorer" artifact (https://claude.ai/artifact/JEpEyijsTpD1y83ut7Zia7), built daily
from TAP_SCHEMA and the ALeRCE team's notes on keys, indexes and relations.

    python tools/build_schema_refs.py [path/to/alerce-book/explorer]

Writes:
  alerce/tap/indexes-and-joins.md   keys, partitions, database indexes, relations, row estimates, notes, tips
  alerce/tap/columns.md             every column: type, unit, description, index flags (grep target)
  alerce/tap/examples.md            the explorer's science workflows (ADQL re-run daily by the explorer)
  tests/baselines/schema_explorer_meta.json   provenance (build dates) for the tests
"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = os.path.join(os.path.dirname(ROOT), "alerce-book", "explorer")
if "/.claude/worktrees/" in ROOT:  # running inside a git worktree of alerce-skills
    DEFAULT_SRC = os.path.join(ROOT.split("/alerce-skills/")[0], "alerce-book", "explorer")
ARTIFACT = "https://claude.ai/artifact/JEpEyijsTpD1y83ut7Zia7"
GENERATED_MARK = "<!-- generated by tools/build_schema_refs.py from the alerce_tap Schema Explorer; do not edit by hand -->"
GROUPS = {"core": "Shared core (all surveys; join on (oid, sid))", "ztf": "ZTF only (sid = 0, magnitudes)",
          "lsst": "LSST only (sid = 1 DIA, 2 solar system; nJy)", "derived": "Derived pipeline products (latest values)",
          "catalog": "External catalogs (via xmatch)", "lookup": "Lookup tables (decode integer ids)"}
JOIN_RULES = [
    "**An object is (sid, oid).** oid alone is not unique across surveys: every join to `object`, or between "
    "per-object tables, goes on both columns. When the survey is known, write the constant "
    "(`object.sid = 0 AND ztf_object.oid = object.oid`).",
    "**A survey table holds one survey.** Without a sid column its sid is implied by its name: `ztf_*` is 0, "
    "`lsst_dia_object` is 1, `lsst_ss_object` is 2. `lsst_detection` has sid (1 or 2); `lsst_forced_photometry` "
    "has sid (always 1).",
    "**Shared table + survey table, one row each way.** Every object has exactly one row in its survey table and "
    "vice versa (a pipeline guarantee). Not yet true for sid 2: "
    "`lsst_ss_object` is empty.",
    "**Page first, then join.** Choose the page from `object` and the tables that filter (ORDER BY … / TOP N), then "
    "join the survey table to those rows only. A join to a table with several rows per object multiplies rows: "
    "narrow it to one row per object, or use EXISTS.",
    "**There are no foreign keys in the database, on purpose** (cost on every pipeline insert; PostgreSQL 16 "
    "ignores them on partitioned tables anyway). The relations below are kept by the pipeline.",
]


def md_escape(s) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def build_indexes(schema: dict) -> str:
    m = schema["meta"]
    out = [
        "# `alerce_tap` keys, indexes and joins (from the Schema Explorer)",
        "",
        f"Generated by `tools/build_schema_refs.py` from the **alerce_tap Schema Explorer** "
        f"([artifact]({ARTIFACT})). Snapshot built {m['built'][:10]}: TAP "
        f"metadata read {m['tap_date']}; keys, indexes and relations as documented by the ALeRCE team.",
        "",
        "TAP tables are views over the PostgreSQL schema `multisurvey`. **The database indexes are what make a "
        "filter fast**: filter first on an indexed column (or the leading primary-key column), otherwise the query "
        "scans a table of up to 1.5 billion rows and times out. Example: `magstat WHERE sid = 1` times out (the "
        "primary key starts with `oid`); `magstat WHERE oid = … AND sid = 1` is instant.",
        "",
        "## What this means for queries",
        "- **Per object**: every per-object table is keyed or indexed on `oid` first, so "
        "`WHERE oid = … AND sid = …` (or `oid IN (…)`) is always fast. Filtering on `sid` alone is not.",
        "- **Object selection**: `object` has indexes on `(sid, n_det)`, `(sid, firstmjd)`, `(sid, lastmjd)` and a "
        "spatial index on `(meanra, meandec)`, so recency, n_det and cone filters are fast.",
        "- **Class selection**: `probability` has a partial index `(sid, probability, oid) WHERE ranking = 1`. "
        "Write `p.sid = … AND p.ranking = 1 … ORDER BY p.probability DESC` (the hunter pattern). There is **no** "
        "index on `classifier_id`/`class_id` (dropped 16 Oct 2026), so those filters ride on the probability scan: "
        "keep `TOP N` and add a probability or `lastmjd` cut (`lastmjd` has a trial index). Since "
        "`object.firstmjd ≤ probability.lastmjd ≤ object.lastmjd`, a date cut on object can be repeated on "
        "`probability.lastmjd`.",
        "- **feature, magstat, xmatch** have only their primary keys (`oid` first): always restrict by oid.",
        "- **TAP_SCHEMA index flags are hints**: they can list columns without a real database index (e.g. "
        "`probability.classifier_id`). Trust the \"extra DB indexes\" column.",
        "",
        "## Join rules",
        *[f"{i}. {r}" for i, r in enumerate(JOIN_RULES, 1)],
        "",
        "## Fast filters at a glance",
        "| table | rows (est.) | primary key | partitioning | extra DB indexes | flagged indexed in TAP_SCHEMA |",
        "|---|---|---|---|---|---|",
    ]
    for t in schema["tables"]:
        tap_idx = [c["name"] for c in t["columns"] if c.get("tapIndexed")]
        idx = "; ".join(f"({i['cols']})" + (f" {i['note']}" if i.get("note") else "") for i in t["indexes"]) or "–"
        out.append(f"| `{t['name']}`{' (EMPTY)' if t.get('empty') else ''} | {md_escape(t.get('rows')) or '–'} | "
                   f"({', '.join(t['pk'])}) | {md_escape(t.get('partition')) or '–'} | {md_escape(idx)} | "
                   f"{', '.join(tap_idx) or '–'} |")
    out += ["", "## Tables: relations, notes and tips"]
    for g, label in GROUPS.items():
        tabs = [t for t in schema["tables"] if t["group"] == g]
        if not tabs:
            continue
        out += ["", f"### {label}"]
        for t in tabs:
            out += ["", f"**`{t['name']}`**: {md_escape(t['description'])}"]
            if t["refs"]:
                out.append("- joins to: " + "; ".join(
                    f"`{r['table']}` on {r['from']} → {r['to']}" + (f" ({r['status']})" if r.get("status") else "")
                    for r in t["refs"]))
            if t["refdBy"]:
                out.append("- referenced by: " + ", ".join(f"`{r['table']}`" for r in t["refdBy"]))
            if t.get("note"):
                out.append(f"- note: {md_escape(t['note'])}")
            if t.get("tip"):
                out.append(f"- tip: {md_escape(t['tip'])}")
            if t.get("dropped"):
                out.append("- dropped indexes: " + "; ".join(t["dropped"]))
    out.append("")
    return "\n".join(out)


def build_columns(schema: dict) -> str:
    m = schema["meta"]
    n = sum(len(t["columns"]) for t in schema["tables"])
    out = [
        "# `alerce_tap` column dictionary",
        "",
        f"All {n} columns of the {len(schema['tables'])} tables with type, unit and description, generated from the "
        f"alerce_tap Schema Explorer ([artifact]({ARTIFACT}); TAP metadata of {m['tap_date']}). "
        "**Search this file (grep) instead of reading it whole.** Flags: PK = primary key, IDX = database index, "
        "TAP = flagged indexed in TAP_SCHEMA. For keys, joins and fast filters see `indexes-and-joins.md`.",
    ]
    for t in schema["tables"]:
        idx_cols = {c.strip().split("::")[0] for i in t["indexes"] for c in i["cols"].split(",")}
        out += ["", f"## {t['name']}", "", md_escape(t["description"]), "",
                "| column | type | unit | flags | description |", "|---|---|---|---|---|"]
        for c in t["columns"]:
            flags = " ".join(f for f, ok in (("PK", c["name"] in t["pk"]), ("IDX", c["name"] in idx_cols),
                                             ("TAP", c.get("tapIndexed"))) if ok)
            out.append(f"| `{c['name']}` | {md_escape(c.get('type'))} | {md_escape(c.get('unit'))} | {flags} | "
                       f"{md_escape(c.get('desc'))} |")
    out.append("")
    return "\n".join(out)


def build_examples(examples: list, results: dict, meta: dict) -> str:
    out = [
        "# Worked TAP workflows (from the Schema Explorer)",
        "",
        f"Eight end-to-end ADQL workflows (4 science cases × LSST/ZTF), copied from the **alerce_tap Schema "
        f"Explorer** ([artifact]({ARTIFACT})). The explorer re-runs every query daily; snapshot of "
        f"{meta['built'][:10]}. Each follows the same pattern: look up ids → look up bands/features → select "
        "candidates → filter by features → light curve (detections, forced photometry) → crossmatch.",
        "",
        "The ids written in the queries (classifier_id, class_id, feature ids, the example oid) were correct on "
        "that date. **Resolve them by name at runtime** (step 1–2 of each workflow) before reusing a query; "
        "class ids are per classifier and feature ids differ per survey.",
    ]
    for ex in examples:
        out += ["", f"## {ex['tab']}"]
        for sv, v in ex["variants"].items():
            out += ["", f"### {ex['tab']} · {sv.upper()}", "", v["goal"]]
            for si, s in enumerate(v["steps"]):
                title, desc, q = s[0], s[1], s[2]
                timing = s[3] if len(s) > 3 and isinstance(s[3], str) else ""
                queries = [("", q)] if isinstance(q, str) else [(lab, qq) for lab, qq in q]
                out += ["", f"**{si + 1}. {title}**" + (f" ({timing})" if timing else ""), "", desc]
                for qi, (lab, qq) in enumerate(queries):
                    res = results.get(f"{ex['id']}/{sv}/{si}/{qi}") or {}
                    nrows = len(res.get("rows", []))
                    hdr = res.get("header", [])
                    note = f"→ {nrows} row(s) on {meta['built'][:10]}" + (f": {', '.join(hdr)}" if hdr else "")
                    if res.get("stale"):
                        note += " (stale)"
                    out += ["", f"*{lab}*" if lab else "", "```sql", qq.strip(), "```", note]
    out.append("")
    return "\n".join(l for l in out)


def main(src: str):
    schema = json.load(open(os.path.join(src, "alerce_tap.json")))
    examples = json.load(open(os.path.join(src, "examples.json")))
    results = json.load(open(os.path.join(src, "example_results.json")))
    skill_tap = os.path.join(ROOT, "alerce", "tap")
    for name, text in (("indexes-and-joins.md", build_indexes(schema)), ("columns.md", build_columns(schema)),
                       ("examples.md", build_examples(examples, results, schema["meta"]))):
        with open(os.path.join(skill_tap, name), "w") as f:
            f.write(GENERATED_MARK + "\n" + text)
        print(f"wrote alerce/tap/{name} ({len(text) // 1024} KB)")
    meta = {k: v for k, v in schema["meta"].items() if k not in ("review", "changes")}  # internal bookkeeping
    meta = dict(meta, tables=len(schema["tables"]),
                columns=sum(len(t["columns"]) for t in schema["tables"]),
                example_queries=sum(1 for k in results), artifact=ARTIFACT)
    with open(os.path.join(ROOT, "tests", "baselines", "schema_explorer_meta.json"), "w") as f:
        json.dump(meta, f, indent=1, sort_keys=True)
        f.write("\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC)
